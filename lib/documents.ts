export function sheetForAttachment(att: BenefitAttachment): DocSheet {
  const known = sheets[att.id];
  if (known) return known;
  const image = att.kind === "image" || /\.(png|jpe?g|webp)$/i.test(att.title);
  return {
    title: att.title,
    kind: image ? "image" : "pdf",
    kicker: image ? "Изображение" : "Документ",
    paragraphs: [
      `Файл «${att.title}» приложен к заявке и доступен HR.`,
      "Содержание открывается здесь, без внешнего хранилища.",
    ],
  };
}
